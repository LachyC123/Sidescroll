// `bridgeIn` / `bridgeOut` so every chapter opens on remnants of the last one
// and closes by foreshadowing the next.
//
// `beats` follow the Section 3 chapter pacing template:
//   arrival - teach - test - rest - twist - climax - departure
// Lengths are in tiles and were chosen so a chapter reads at roughly the
// minute counts the template gives.

export const ACT_OF = { 1: [0, 4], 2: [5, 8], 3: [9, 11], 4: [12, 13], 5: [14, 15] };

export function actFor(index) {
  for (const [act, [a, b]] of Object.entries(ACT_OF)) {
    if (index >= a && index <= b) return Number(act);
  }
  return 1;
}

