export function chapterAt(i) { return CHAPTERS[Math.max(0, Math.min(CHAPTERS.length - 1, i))]; }
export function nextChapterId(id) {
  const i = CHAPTERS.findIndex((c) => c.id === id);
  return i >= 0 && i < CHAPTERS.length - 1 ? CHAPTERS[i + 1].id : null;
}

